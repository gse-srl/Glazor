using Glazor.Grds;
using Glazor.Grds.Filters;
using Glazor.Grds.Mdls;
using Glazor.Misc;
using System.Text.Json;

namespace Glazor.Tests;

/// <summary>
/// A library user extending a built-in definition is the case the open hierarchy exists for, and it is where
/// the identity rules bite: <see cref="AFilterDef.Equals(AFilterDef?)"/> compares the record returned by
/// <c>CreateSerRecord()</c>, so state a subclass adds is only part of its identity if the subclass extends
/// that record too. These tests pin both halves — a subclass that does extend it, and one that does not.
/// </summary>
public class DynaValuesInSetDefSubclassTests
{
    public record CompanyRole(int Id, int CompanyId, string Description);

    public class ByCompanyRolesFDef : DynaValuesInSetDef<ByCompanyRolesFDef, CompanyRole, int>
    {
        public int? CompanyId { get; set; }

        protected ByCompanyRolesFDef() : this(false)
        {
        }

        public ByCompanyRolesFDef(bool startFull) : base(true, cr => cr.Id, startFull)
        {
        }

        public override ByCompanyRolesFDef Clone()
        {
            return new(StartFull())
            {
                CompanyId = CompanyId,
                IncludeNullOrEmpty = IncludeNullOrEmpty,
                AllKeys = AllKeys == null ? null : new(AllKeys),
                Selected = new(Selected),
            };
        }

        protected override DataGridModel<CompanyRole> CreateAllValuesModel()
        {
            DataGridModel<CompanyRole> model = new DataGridModel<CompanyRole>()
            {
                ItemKeyFn = x => x.Id,
            };
            model.AddColumn("id", new Column<CompanyRole, int>("Id")
            {
                Alignment = Alignment.Center,
                PreferredSize = 5,
            }, v => v.Id);
            model.AddColumn("description", new Column<CompanyRole, string?>("Ruolo")
            {
                Alignment = Alignment.Center,
                PreferredSize = 20,
            }, v => v.Description);
            return model;
        }

        protected override async ValueTask<IList<CompanyRole>> RetrieveAllValuesAsync(CancellationToken ct)
        {
            CompanyId = 111;
            return [new(1, 111, "admin"), new(2, 111, "user"), new(3, 111, "guest")];
        }

        public record BCRSerialized(IEnumerable<int>? AllKeys, bool IncludeNullOrEmpty, IEnumerable<int> Selected, int? CompanyId)
            : DynaValuesInSetDef<ByCompanyRolesFDef, CompanyRole, int>.Serialized(AllKeys, IncludeNullOrEmpty, Selected)
        {
            protected static readonly new IEqualityComparer<BCRSerialized> comparer = EqComparers.Combo<BCRSerialized>(l => l
                .Add(l => l?.CompanyId)
            );

            public virtual bool Equals(BCRSerialized? other)
            {
                if (!base.Equals(other))
                    return false;
                return comparer.Equals(this, other);
            }

            //public override bool Equals(object? obj) Not needed, generated by the compiler ...

            public override int GetHashCode()
            {
                return HashCode.Combine(base.GetHashCode(), comparer.GetHashCode(this));
            }
        }

        protected override BCRSerialized CreateSerRecord() => new BCRSerialized(AllKeys, IncludeNullOrEmpty, Selected, CompanyId);

        public override ByCompanyRolesFDef Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
        {
            BCRSerialized ser = JsonSerializer.Deserialize<BCRSerialized>(ref reader, options).RequireNotNull();
            ByCompanyRolesFDef res = new(false)  // always false when deserialized
            {
                CompanyId = ser.CompanyId,
                IncludeNullOrEmpty = ser.IncludeNullOrEmpty,
                AllKeys = ser.AllKeys?.ToHashSet(),
                Selected = ser.Selected.ToHashSet(),
            };
            return res;
        }

        public ByCompanyRolesFDef InjectParamsInto(ByCompanyRolesFDef toBeInjected)
        {
            return new(toBeInjected.StartFull())
            {
                CompanyId = toBeInjected.CompanyId,
                IncludeNullOrEmpty = toBeInjected.IncludeNullOrEmpty,
                AllKeys = toBeInjected.AllKeys,
                Selected = toBeInjected.Selected,
            };
        }
    }

    /// <summary>
    /// The added field has to reach the payload and come back. Asserting on the JSON text as well as the
    /// round trip separates "the value survived" from "the value was written at all" — a CreateSerRecord that
    /// still returned the base record would fail the first assertion and could accidentally pass a
    /// round-trip check that only compared shared state.
    /// </summary>
    [Test]
    public async Task ASubclassFieldReachesThePayloadAndComesBackTest()
    {
        ByCompanyRolesFDef def = new ByCompanyRolesFDef(true);
        await def.PopulateAsync();

        string json = JsonSerializer.Serialize<AFilterDef>(def);
        AFilterDef restored = JsonSerializer.Deserialize<AFilterDef>(json).RequireNotNull();

        Assert.Multiple(() =>
        {
            Assert.That(json, Does.Contain("\"CompanyId\":111"), "the field must be written");
            Assert.That(restored, Is.TypeOf<ByCompanyRolesFDef>(), "and the concrete type restored");
            Assert.That(((ByCompanyRolesFDef)restored).CompanyId, Is.EqualTo(111));
            Assert.That(((ByCompanyRolesFDef)restored).Selected, Is.EquivalentTo(new[] { 1, 2, 3 }));
            Assert.That(restored, Is.EqualTo(def), "a round trip is the same filter");
            Assert.That(restored.GetHashCode(), Is.EqualTo(def.GetHashCode()));
        });

        def.Selected.Remove(2);

        string json2 = JsonSerializer.Serialize<AFilterDef>(def);
        AFilterDef restored2 = JsonSerializer.Deserialize<AFilterDef>(json2).RequireNotNull();

        Assert.Multiple(() =>
        {
            Assert.That(json2, Does.Contain("\"CompanyId\":111"), "the field must be written");
            Assert.That(restored2, Is.TypeOf<ByCompanyRolesFDef>(), "and the concrete type restored");
            Assert.That(((ByCompanyRolesFDef)restored2).CompanyId, Is.EqualTo(111));
            Assert.That(((ByCompanyRolesFDef)restored2).Selected, Is.EquivalentTo(new[] { 1, 3 }));
            Assert.That(restored2, Is.EqualTo(def), "a round trip is the same filter");
            Assert.That(restored2.GetHashCode(), Is.EqualTo(def.GetHashCode()));
        });

        Assert.Multiple(() =>
        {
            Assert.That(restored2, Is.Not.EqualTo(restored));
            Assert.That(restored2.GetHashCode(), Is.Not.EqualTo(restored.GetHashCode()));
        });
    }

    public record Tag(int Id, string Name);

    /// <summary>A collection of tag ids, a value type, whose dialog lists the tags, rows of a type of their own.</summary>
    public class TagsFDef : ADynaValuesInSetDef<TagsFDef, int, Tag, int>
    {
        protected TagsFDef() : this(false)
        {
        }

        public TagsFDef(bool startFull) : base(true, id => id, startFull)
        {
        }

        protected override int RowToKey(Tag row) => row.Id;

        public override TagsFDef Clone() => new(StartFull())
        {
            IncludeNullOrEmpty = IncludeNullOrEmpty,
            AllKeys = AllKeys == null ? null : new(AllKeys),
            Selected = new(Selected),
        };

        protected override DataGridModel<Tag> CreateAllValuesModel()
        {
            DataGridModel<Tag> model = new() { ItemKeyFn = t => t.Id };
            model.AddColumn("name", new Column<Tag, string>("Tag") { PreferredSize = 20 }, t => t.Name);
            return model;
        }

        protected override ValueTask<IList<Tag>> RetrieveAllValuesAsync(CancellationToken ct) =>
            ValueTask.FromResult<IList<Tag>>([new(1, "red"), new(2, "green"), new(3, "blue")]);

        public override TagsFDef Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
        {
            Serialized ser = JsonSerializer.Deserialize<Serialized>(ref reader, options).RequireNotNull();
            return new(ser.StartFull)
            {
                IncludeNullOrEmpty = ser.IncludeNullOrEmpty,
                AllKeys = ser.AllKeys?.ToHashSet(),
                Selected = ser.Selected.ToHashSet(),
            };
        }

        private static readonly FilterDefRendererType<TagsFDefRenderer> rendererType = new();

        public override FilterDefRendererType Renderer() => rendererType;
    }

    public class TagsFDefRenderer : ADynaValuesInSetDefRenderer<TagsFDef, int, Tag, int>
    {
    }

    /// <summary>
    /// Rows of their own: the selection holds the keys the rows give, a collection passes on its items' keys, and the
    /// definition comes back from JSON the same.
    /// </summary>
    [Test]
    public async Task RowsOfTheirOwnSelectAndFilterByKeyTest()
    {
        TagsFDef def = new(startFull: false);
        IList<Tag> rows = await def.PopulateAsync();
        def.CreateSetSelectionModel().Select(rows[1], true);

        AFilterDef restored = JsonSerializer.Deserialize<AFilterDef>(JsonSerializer.Serialize<AFilterDef>(def)).RequireNotNull();
        Assert.Multiple(() =>
        {
            Assert.That(def.Selected, Is.EquivalentTo(new[] { 2 }));
            Assert.That(def.Includes(new[] { 1, 2 }.AsQueryable()), Is.True);
            Assert.That(def.Includes(new[] { 1, 3 }.AsQueryable()), Is.False);
            Assert.That(def.Includes(Array.Empty<int>().AsQueryable()), Is.True, "empty, with IncludeNullOrEmpty");
            Assert.That(restored, Is.TypeOf<TagsFDef>().And.EqualTo(def));
        });
    }

    /// <summary>A definition that always refuses a null or empty collection, whatever <c>IncludeNullOrEmpty</c> says.</summary>
    public class NeverEmptyTagsFDef : TagsFDef
    {
        public NeverEmptyTagsFDef() : base(false)
        {
        }

        public override bool MustIncludeNullOrEmpty() => false;
    }

    /// <summary>Two definitions that filter alike are the same filter, even when a property they ignore differs.</summary>
    [Test]
    public void IdentityFollowsWhatTheDefinitionFiltersOnTest()
    {
        NeverEmptyTagsFDef a = new() { IncludeNullOrEmpty = true }, b = new() { IncludeNullOrEmpty = false };
        a.Selected.Add(1);
        b.Selected.Add(1);
        IQueryable<int> empty = Array.Empty<int>().AsQueryable();
        Assert.Multiple(() =>
        {
            Assert.That(a.Includes(empty), Is.False.And.EqualTo(b.Includes(empty)), "they filter alike");
            Assert.That(a, Is.EqualTo(b));
            Assert.That(a.GetHashCode(), Is.EqualTo(b.GetHashCode()));
        });
    }
}
