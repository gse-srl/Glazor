using Glazor.Grds.Mdls;
using Glazor.Misc;
using Microsoft.Extensions.Logging;
using System.Collections.Immutable;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Glazor.Grds.Filters;

/// <summary>
/// The filter of an enum column: the members selected out of <see cref="AllValues"/>, and whether a null value passes. Membership
/// is exact, so a <c>[Flags]</c> combination passes only when that very value is selected.
/// </summary>
public class EnumDef : ASetDef<EnumDef, Enum>
{
    private static readonly ILogger<EnumDef> logger = LoggerSupport.Logger<EnumDef>();

    /// <summary>The column's type as given to the constructor, the enum or its nullable.</summary>
    public Type EnumType { get; }

    /// <summary>Whether a null value passes the filter; true by default.</summary>
    public bool IncludeNull { get; set; } = true;
    /// <summary>The members selected; given at construction, then changed in place, as the dialog selects into this very set.</summary>
    public HashSet<Enum> Selected { get; init; }

    /// <summary>Every member of the enum, the candidates the dialog offers.</summary>
    public IReadOnlySet<Enum> AllValues { get; }

    /// <summary>
    /// Just the prototype c-tor, we use it upon deserialization
    /// </summary>
    internal EnumDef()
    {
        EnumType = typeof(bool);
        AllValues = null!;
        Selected = null!;
    }

    /// <summary>A filter over the members of <paramref name="enumType"/>, the enum or its nullable; <paramref name="startFull"/> selects them all.</summary>
    public EnumDef(Type enumType, bool startFull)
    {
        Type etype = Nullable.GetUnderlyingType(enumType) ?? enumType;
        if (!etype.IsEnum)
            throw new ArgumentException($"Not an enum: {enumType}");
        HashSet<Enum> avs = new();
        foreach (Enum e in Enum.GetValues(etype))
        {
            avs.Add(e);
        }
        AllValues = avs.ToImmutableHashSet();
        EnumType = enumType;
        this.Selected = startFull ? new(avs) : new();
    }

    /// <inheritdoc/>
    public override Type GetValueType() => EnumType;

    /// <inheritdoc/>
    public override EnumDef Clone()
    {
        return new EnumDef(EnumType, false)
        {
            IncludeNull = this.IncludeNull,
            Selected = new(this.Selected),
        };
    }
    /// <summary>A selection model over <see cref="AllValues"/> that selects into <see cref="Selected"/> itself, not a copy.</summary>
    public SetSelectionModelWithSelectAll<Enum> CreateSetSelectionModel()
    {
        return new SetSelectionModelWithSelectAll<Enum>(AllValues, this.Selected, defensiveCopy: false);   // the dialog selects into the definition's own set
    }

    /// <inheritdoc/>
    public override bool IsVoid()
    {
        return MustIncludeNull() && Selected.SetEquals(AllValues);
    }

    /// <inheritdoc/>
    public override bool MustIncludeNull() => IncludeNull;

    /// <inheritdoc/>
    public override IReadOnlySet<Enum> GetSelected()
    {
        return Selected;
    }

    private static readonly FilterDefRendererType<EnumDefRenderer> rendererType = new();

    /// <inheritdoc/>
    public override FilterDefRendererType Renderer() => rendererType;   // a subclass may name its own editor

    // Always written: strict options require them, and options that skip nulls or defaults would leave them out

    /// <summary>The definition as a memento stores it.</summary>
    /// <param name="EnumType">The enum's type name.</param>
    /// <param name="IncludeNull">Whether a null value passes.</param>
    /// <param name="Selected">The names of the members that pass.</param>
    public record Serialized(string EnumType, [property: JsonIgnore(Condition = JsonIgnoreCondition.Never)] bool IncludeNull, IEnumerable<string> Selected) : AFilterDefSer
    {
        /// <summary>The equality the record's <c>Equals</c> uses.</summary>
        protected static readonly IEqualityComparer<Serialized> comparer = EqComparers.Combo<Serialized>(l => l
             .Add(l => l?.EnumType)
             .Add(l => l?.IncludeNull)
             .Add(l => l?.Selected, EqComparers.ForSet<string>()));   // Selected is a set

        /// <inheritdoc/>
        public virtual bool Equals(Serialized? other)
        {
            if (!base.Equals(other)) 
                return false;
            return comparer.Equals(this, other);
        }

        //public override bool Equals(object? obj) Not needed, generated by the compiler ...

        /// <inheritdoc/>
        public override int GetHashCode()
        {
            return HashCode.Combine(base.GetHashCode(), comparer.GetHashCode(this));
        }
    }

    /// <inheritdoc/>
    protected override Serialized CreateSerRecord() => new Serialized(FilterDefFactory.TypeName(EnumType),
            IncludeNull, Selected.Select(e => e.ToString()).ToArray());

    /// <inheritdoc/>
    public override EnumDef Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
    {
        Serialized ser = JsonSerializer.Deserialize<Serialized>(ref reader, options).RequireNotNull();
        // the factory reading this definition, however the host attached it: its allow-list applies here too
        Type enumType = FilterDefFactory.Reading.ResolveEnumType(ser.EnumType);
        Type etype = Nullable.GetUnderlyingType(enumType) ?? enumType;
        if (!etype.IsEnum)
            throw new JsonException($"Not an enum: {ser.EnumType}");
        EnumDef res = new EnumDef(enumType, false) { IncludeNull = ser.IncludeNull };
        foreach (string ename in ser.Selected ?? [])
        {
            // only the text CreateSerRecord writes: a number, or a list on a plain enum, is refused
            if (Enum.TryParse(etype, ename, out object? v) && Enum.IsDefined(etype, v!) && v.ToString() == ename)
                res.Selected.Add((Enum)v!);
            else   // a renamed member loses its selection, not the whole memento
                logger.LogWarning("Persisted member {Member} of {EnumType} no longer exists: dropped", ename, etype.Name);
        }
        return res;
    }
}
